import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** nginx snippet written into the build output; the Dockerfile moves it into nginx's config */
export const CSP_SNIPPET_FILE = "nginx-csp-policy.conf";

// Inline <script> elements without a src. JSON-LD and other data blocks are
// never executed, so CSP does not apply to them.
const INLINE_SCRIPT = /<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g;
const DATA_BLOCK_TYPE = /\btype=["']?application\/(?:ld\+)?json/i;

// The policy must precede every script: it goes right after the charset, or
// after the doctype on pages without one (such as Astro's redirect pages)
const CHARSET_META = /<meta charset="[^"]*">/i;
const DOCTYPE = /<!doctype html>/i;

/**
 * Collect the sha256 hashes of every executable inline script in the given
 * HTML documents.
 */
export function collectInlineScriptHashes(documents) {
  const hashes = new Set();
  for (const html of documents) {
    for (const [, attributes, body] of html.matchAll(INLINE_SCRIPT)) {
      if (DATA_BLOCK_TYPE.test(attributes)) continue;
      hashes.add(`'sha256-${createHash("sha256").update(body).digest("base64")}'`);
    }
  }
  return [...hashes].sort();
}

/**
 * Build the site's Content-Security-Policy, limited to directives that work
 * in a <meta> element so every host enforces it without configuration.
 *
 * The hashes are site-wide rather than per page: with Astro's ClientRouter the
 * first page's policy stays in force while later pages' scripts run.
 * - 'wasm-unsafe-eval' lets Pagefind instantiate its WebAssembly search index.
 * - style-src needs 'unsafe-inline' for Shiki's per-token style attributes.
 * - data: images are used by the Pagefind UI stylesheet.
 *
 * Header-only directives (frame-ancestors, reporting) are added by the server
 * configuration; see nginx.conf.
 */
export function buildContentSecurityPolicy(scriptHashes) {
  return [
    "default-src 'self'",
    ["script-src 'self' 'wasm-unsafe-eval'", ...scriptHashes].join(" "),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
  ].join("; ");
}

/** Insert the policy as a <meta http-equiv> element ahead of any script */
export function injectCspMeta(html, policy) {
  const meta = `<meta http-equiv="Content-Security-Policy" content="${policy}">`;
  const anchor = CHARSET_META.test(html) ? CHARSET_META : DOCTYPE;
  if (!anchor.test(html)) {
    throw new Error("Cannot inject Content-Security-Policy: no <meta charset> or doctype found");
  }
  return html.replace(anchor, (match) => match + meta);
}

async function listHtmlFiles(dir) {
  const entries = await readdir(dir, { recursive: true });
  return entries.filter((file) => file.endsWith(".html")).map((file) => path.join(dir, file));
}

/**
 * Astro integration that hashes every inline script in the built site, then
 * embeds the matching policy in each page as a <meta> element and writes an
 * nginx snippet defining it as $site_csp for use in a response header.
 */
export function cspIntegration() {
  return {
    name: "csp",
    hooks: {
      "astro:build:done": async ({ dir, logger }) => {
        const outDir = fileURLToPath(dir);
        const files = await listHtmlFiles(outDir);
        const documents = await Promise.all(files.map((file) => readFile(file, "utf8")));
        const hashes = collectInlineScriptHashes(documents);
        const policy = buildContentSecurityPolicy(hashes);

        await Promise.all(
          files.map((file, i) => writeFile(file, injectCspMeta(documents[i], policy)))
        );
        await writeFile(
          path.join(outDir, CSP_SNIPPET_FILE),
          `# Generated by csp-integration.mjs at build time. Do not edit.\n` +
            `set $site_csp "${policy}";\n`
        );
        logger.info(
          `Content-Security-Policy covers ${hashes.length} inline script(s) across ${files.length} pages`
        );
      },
    },
  };
}
